#!/usr/bin/env python3
"""
Y-Maze Outcome Measures Calculator

Reads labeled_final.csv files generated by create_ymaze_timing.py and calculates
behavioral outcome measures at trial, environment, and task levels.

Usage:
    python create_ymaze_outcomes.py                          # Use default output dir
    python create_ymaze_outcomes.py --output-dir /path       # Override output directory
    python create_ymaze_outcomes.py --help                   # Show all options
"""

